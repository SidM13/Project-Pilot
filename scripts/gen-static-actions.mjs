// Generates browser copies of the server actions for the static GitHub Pages build:
// identical code minus the "use server" directive. In that build, next.config.ts
// aliases @/actions/* to these files and swaps the database client for the
// in-browser demo store, so the same validated action logic runs locally.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const ACTIONS = ["shared", "projects", "tasks", "milestones", "budget", "team", "simulations", "ai"];
const OUT = "src/static/generated/actions";
mkdirSync(OUT, { recursive: true });
for (const name of ACTIONS) {
  const source = readFileSync(`src/actions/${name}.ts`, "utf8").replace(/^"use server";\s*\n/m, "");
  writeFileSync(`${OUT}/${name}.ts`, `// GENERATED by scripts/gen-static-actions.mjs from src/actions/${name}.ts — do not edit.\n${source}`);
}
console.log(`static actions: generated ${ACTIONS.length} files`);
